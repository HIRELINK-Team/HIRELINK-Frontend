function Checkbox({ checked }: { checked: boolean }) {
  return (
    <span
      aria-hidden="true"
      className={`grid size-5 shrink-0 place-items-center rounded-[6px] border ${
        checked
          ? 'border-[#00B894] bg-[#00B894] text-white'
          : 'border-[rgba(112,115,124,0.32)] bg-white'
      }`}
    >
      {checked ? <span className="text-[14px] leading-none">✓</span> : null}
    </span>
  );
}

function isListItem(paragraph: string) {
  return paragraph.startsWith('•') || /^\d+\. /.test(paragraph);
}

function TermSectionBody({ body }: { body: readonly string[] }) {
  const content: ReactNode[] = [];

  for (let index = 0; index < body.length;) {
    if (!isListItem(body[index])) {
      content.push(
        <p className="m-0 break-keep" key={`${body[index]}-${index}`}>
          {body[index]}
        </p>,
      );
      index += 1;
      continue;
    }

    const listItems: string[] = [];

    while (index < body.length && isListItem(body[index])) {
      listItems.push(body[index]);
      index += 1;
    }

    content.push(
      <div
        className="flex flex-col gap-[6px] rounded-[12px] bg-white px-4 py-3 text-[13px] leading-[1.5] text-[#707577] shadow-[1px_1px_20px_rgba(0,0,0,0.04)]"
        key={`list-${listItems.join('-')}`}
      >
        {listItems.map((item) => (
          <p className="m-0 break-keep" key={item}>
            {item}
          </p>
        ))}
      </div>,
    );
  }

  return <div className="mt-2 flex flex-col gap-2">{content}</div>;
}

